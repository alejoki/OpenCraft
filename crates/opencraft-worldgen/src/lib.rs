//! Neutral world generation for OpenCraft.
//!
//! This crate will own biome/tag data, height and ruin queries, prefab and
//! village codecs/plans/placement, loot vocabulary and terrain generation over
//! raw `u16` block ids, carrying no game block id, session state, GPU or
//! windowing dependency. Skeleton only: modules and dependencies land with the
//! worldgen slices.
